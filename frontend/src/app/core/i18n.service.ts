const DICTIONARIES: Record<SupportedLang, typeof VI_TRANSLATIONS> = {
  vi: VI_TRANSLATIONS,
  en: EN_TRANSLATIONS,
};

const STORAGE_KEY = 'rental_lang';

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly currentLang = signal<SupportedLang>(this.detectInitialLang());

  readonly isVi = computed(() => this.currentLang() === 'vi');
  readonly isEn = computed(() => this.currentLang() === 'en');

  constructor() {
    this.updateHtmlLang(this.currentLang());
  }

  private detectInitialLang(): SupportedLang {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'vi' || stored === 'en') {
        return stored;
      }
    } catch {
      // ignore
    }
    // Default to Vietnamese for RentalHub
    return 'vi';
  }

  setLang(lang: SupportedLang): void {
    if (this.currentLang() === lang) return;
    this.currentLang.set(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // ignore
    }
    this.updateHtmlLang(lang);
  }

  toggleLang(): void {
    this.setLang(this.currentLang() === 'vi' ? 'en' : 'vi');
  }

  private updateHtmlLang(lang: SupportedLang): void {
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = lang;
    }
  }

  /**
   * Translate a dotted key string (e.g. 'nav.dashboard', 'common.save')
   * with optional parameter interpolation {name}
   */
  t(key: string, params?: Record<string, string | number>): string {
    const lang = this.currentLang();
    const dict = DICTIONARIES[lang] || DICTIONARIES.vi;

    let value: unknown = dict;
    const parts = key.split('.');

    for (const part of parts) {
      if (value && typeof value === 'object' && part in value) {
        value = (value as Record<string, unknown>)[part];
      } else {
        // Fallback to English dictionary if key missing in target language
        value = this.getFallback(key);
        break;
      }
    }

    if (typeof value !== 'string') {
      return key;
    }

    if (!params) {
      return value;
    }

    // Interpolate {paramName}
    return value.replace(/\{(\w+)\}/g, (match, paramKey) => {
      return params[paramKey] !== undefined ? String(params[paramKey]) : match;
    });
  }

  private getFallback(key: string): string {
    let value: unknown = DICTIONARIES.en;
    const parts = key.split('.');
    for (const part of parts) {
      if (value && typeof value === 'object' && part in value) {
        value = (value as Record<string, unknown>)[part];
      } else {
        return key;
      }
    }
    return typeof value === 'string' ? value : key;
  }
}
